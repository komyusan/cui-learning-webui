#!/bin/sh
# =================================================================
# cui-learning-sandbox コンテナ用 entrypoint
# =================================================================
# このスクリプトはサンドボックスコンテナ起動時に実行される。
# ツールとしての実行（hydra, aircrack-ng 等）とデーモン起動モードの
# 両方に対応する。
#
# 用途:
#   1. hydra/aircrack-ng 等のコマンドを直接実行するとき
#      → executor.py から command=["hydra", "-l", "admin", ...] のように呼ばれる
#      → 本スクリプトが SSH を起動してから exec hydra ... を実行する
#
#   2. 将来的に永続サービスとして起動するとき（拡張用）
# =================================================================

# Hydra が自身の SSH サーバー (127.0.0.1) に接続する演習に備えて
# SSH デーモンをバックグラウンドで起動しておく
if [ -d /var/run/sshd ]; then
    /usr/sbin/sshd 2>/dev/null || true
fi

# 渡された引数をそのまま実行する
# executor.py から command=["hydra", "-l", "admin", ...] が渡される
exec "$@"
